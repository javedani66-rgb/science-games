def band(y0, y1, color, seed, w=360, amp=2.6, step=18):
    """نوار رنگ تخت با لبهٔ بالای دست‌کشیده (به‌جای گرادیان)؛ بدون خط دور"""
    top = brush([(-4, y0), (w + 4, y0)], amp, seed, step, False)
    pts = top + [(w + 4, y1), (-4, y1)]
    return f'<path d="{pd(pts)}" fill="{color}"/>'
